const sqlite3 = require('sqlite3').verbose();
const fs = require('fs');

const db = new sqlite3.Database('database.sqlite');
const out = fs.createWriteStream('supabase_migration.sql');

// Postgres Schema definitions
const schema = `
-- Disable triggers/FK checks temporarily during massive insert
SET session_replication_role = 'replica';

DROP TABLE IF EXISTS messages, users, room_names, follows, blocks, room_bans CASCADE;

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE,
  email TEXT UNIQUE,
  password TEXT,
  "isVerified" INTEGER DEFAULT 0,
  "verificationToken" TEXT,
  "resetToken" TEXT,
  "resetTokenExpiry" BIGINT,
  "displayName" TEXT,
  "avatarPath" TEXT,
  "notifyApp" INTEGER DEFAULT 1,
  "notifyJoin" INTEGER DEFAULT 1,
  "notifyMessages" INTEGER DEFAULT 1,
  "notifyFriendRequests" INTEGER DEFAULT 1,
  "notifyLeave" INTEGER DEFAULT 1,
  language TEXT DEFAULT 'en',
  country TEXT,
  "showCountry" INTEGER DEFAULT 1,
  bio TEXT DEFAULT NULL,
  "pinnedRooms" TEXT DEFAULT '[]',
  "lastSeen" TEXT DEFAULT '{}'
);

CREATE TABLE messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL,
  "senderId" TEXT,
  "senderName" TEXT,
  "targetId" TEXT,
  "targetName" TEXT,
  "roomId" TEXT,
  message TEXT,
  nonce TEXT,
  "ephemeralPublicKey" TEXT,
  timestamp BIGINT NOT NULL,
  "replyTo" TEXT,
  "hiddenFor" TEXT,
  reactions TEXT DEFAULT '{}',
  "mediaType" TEXT,
  "mediaUrl" TEXT
);

CREATE TABLE room_names (
  "roomId" TEXT PRIMARY KEY,
  "roomName" TEXT NOT NULL,
  "hostUsername" TEXT,
  "isPublic" INTEGER DEFAULT 0,
  category TEXT DEFAULT 'other',
  "thumbnailPath" TEXT,
  settings TEXT DEFAULT '{}',
  permissions TEXT DEFAULT '{}'
);

CREATE TABLE follows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "followerId" TEXT NOT NULL,
  "followingId" TEXT NOT NULL,
  status TEXT DEFAULT 'pending',
  "createdAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  UNIQUE("followerId", "followingId")
);

CREATE TABLE blocks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  blocker TEXT NOT NULL,
  blocked TEXT NOT NULL,
  "createdAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(blocker, blocked)
);

CREATE TABLE room_bans (
  "roomId" TEXT NOT NULL,
  username TEXT NOT NULL,
  UNIQUE("roomId", username)
);
\n`;

out.write(schema);

// Helper to escape values for SQL
function esc(val) {
  if (val === null || val === undefined) return 'NULL';
  if (typeof val === 'number') return val;
  return "'" + String(val).replace(/'/g, "''") + "'";
}

// Ensure asynchronous extraction happens sequentially
const tables = ['users', 'messages', 'room_names', 'follows', 'blocks', 'room_bans'];

async function exportTable(table) {
  return new Promise((resolve) => {
    db.all("SELECT * FROM " + table, (err, rows) => {
      if (err || rows.length === 0) return resolve();
      
      out.write("\n-- Data for " + table + "\n");
      for (const row of rows) {
        // Skip invalid rows that violate Postgres NOT NULL primary key constraints
        if (table === 'room_names' && row.roomId === null) continue;
        if ((table === 'users' || table === 'messages' || table === 'follows' || table === 'blocks') && row.id === null) continue;

        const keys = Object.keys(row).map(k => '"' + k + '"').join(', ');
        const values = Object.values(row).map(esc).join(', ');
        out.write("INSERT INTO " + table + " (" + keys + ") VALUES (" + values + ");\n");
      }
      resolve();
    });
  });
}

(async () => {
  for (const t of tables) {
    await exportTable(t);
  }
  out.write("\n\n-- Re-enable triggers\nSET session_replication_role = 'origin';\n");
  out.end();
  console.log("Migration script 'supabase_migration.sql' generated successfully!");
  db.close();
})();
