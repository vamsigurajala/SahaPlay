const searchTargetsKeys = Object.keys(searchTargets);
let replaceCount = 0;
for (const lang of searchTargetsKeys) {
  const searchStr = searchTargets[lang];
  const transObj = translations[lang];
  if (!transObj) continue;
  
  // Format the translation entries to insert
  const linesToInsert = Object.entries(transObj).map(([k, v]) => {
    const escapedVal = v.replace(/"/g, '\\"').replace(/\n/g, '\\n');
    return `      "${k}": "${escapedVal}",`;
  }).join('\n');
  
  const replacementStr = `${searchStr}\n${linesToInsert}`;
  
  const occurrences = content.split(searchStr).length - 1;
  if (occurrences === 1) {
    content = content.replace(searchStr, replacementStr);
    replaceCount++;
  } else {
    console.error(`Could not find search string for ${lang} or multiple found: ${searchStr}`);
  }
}

if (replaceCount === searchTargetsKeys.length) {
  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`Successfully inserted core safety translations for ${replaceCount} languages!`);
} else {
  console.error(`Only successfully replaced ${replaceCount} out of ${searchTargetsKeys.length} languages. File was NOT saved.`);
  process.exit(1);
}
