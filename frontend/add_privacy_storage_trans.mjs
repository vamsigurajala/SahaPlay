let injected = 0;

for (const [lang, keys] of Object.entries(translations)) {
  // We locate the insertion point for this language.
  // The structure is:
  //   "lang": {
  //     "translation": {
  //
  // Let's search for `"${lang}": {` (or `"${lang}":{`) first.
  let langIdx = content.indexOf(`"${lang}": {`);
  if (langIdx === -1) {
    langIdx = content.indexOf(`"${lang}":{`);
  }
  
  if (langIdx === -1) {
    console.warn(`[WARN] Could not find lang block for: ${lang}`);
    continue;
  }
  
  // Find the next `"translation": {` (or `"translation":{`) after the lang block start
  let transIdx = content.indexOf(`"translation": {`, langIdx);
  if (transIdx === -1) {
    transIdx = content.indexOf(`"translation":{`, langIdx);
  }
  
  if (transIdx === -1) {
    console.warn(`[WARN] Could not find translation block for: ${lang}`);
    continue;
  }
  
  // Find the next newline after `"translation": {`
  const afterBrace = content.indexOf('\n', transIdx);
  if (afterBrace === -1) {
    console.warn(`[WARN] Could not find newline after translation brace for: ${lang}`);
    continue;
  }
  
  // Build the list of key-value pairs to insert
  let insertion = '';
  for (const [key, value] of Object.entries(keys)) {
    // Check if key already exists in the file for this language
    // To be safe and precise, we check if the key exists within this language's translation block
    // Find next closing brace of translation block to define search range
    const nextLangIdx = content.indexOf('}', afterBrace); // simple end block estimate
    const searchRange = content.slice(langIdx, nextLangIdx > 0 ? nextLangIdx + 5000 : langIdx + 10000);
    
    if (searchRange.includes(`"${key}":`)) {
      console.log(`[SKIP] ${lang}.${key} already exists`);
      continue;
    }
    
    const escapedValue = value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
    // Indent: 6 spaces inside translation block
    insertion += `      "${key}": "${escapedValue}",\n`;
    injected++;
  }
  
  if (insertion) {
    content = content.slice(0, afterBrace + 1) + insertion + content.slice(afterBrace + 1);
    console.log(`[OK] Injected translations for: ${lang}`);
  }
}

