// A painting's text in the visitor's language (the Indian ones carry their own Hindi and
// Telugu text; every other painting is English only).
export function localizedPainting(art, lang) {
  if (!art) return art;
  const over = art.i18n && art.i18n[lang];
  return over ? { ...art, ...over } : art;
}
